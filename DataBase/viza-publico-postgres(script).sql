-- ---------- 0. REINICIO: borra las tablas anteriores y sus datos ----------
DROP TABLE IF EXISTS historial_estado   CASCADE;
DROP TABLE IF EXISTS propuesta_diseno   CASCADE;
DROP TABLE IF EXISTS media_trabajo      CASCADE;
DROP TABLE IF EXISTS trabajo_galeria    CASCADE;
DROP TABLE IF EXISTS cuenta_cliente     CASCADE;
DROP TABLE IF EXISTS pedido             CASCADE;
DROP TABLE IF EXISTS categoria_trabajo  CASCADE;
DROP TABLE IF EXISTS cliente            CASCADE;
DROP TABLE IF EXISTS usuario            CASCADE;
 
DROP TYPE IF EXISTS tipo_media;
DROP TYPE IF EXISTS estado_pedido;
DROP TYPE IF EXISTS estado_propuesta;
 
-- Para generar hashes BCrypt de las cuentas de ejemplo
CREATE EXTENSION IF NOT EXISTS pgcrypto;
 
-- ---------- 1. Tablas del sistema interno ----------
CREATE TABLE usuario (
    id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(150) NOT NULL,
    rol     VARCHAR(30)            -- administrador, secretaria, diseno, taller
);
 
CREATE TABLE cliente (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR(150) NOT NULL,
    telefono        VARCHAR(30),
    email           VARCHAR(150),
    fecha_registro  TIMESTAMP DEFAULT NOW()
);
 
-- ---------- 2. Catálogo ----------
CREATE TABLE categoria_trabajo (
    id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre              VARCHAR(100) NOT NULL,
    slug                VARCHAR(100) NOT NULL UNIQUE,   -- para la URL, ej: letras-inox
    descripcion         TEXT,
    imagen_portada_url  VARCHAR(500),
    orden               INT DEFAULT 0,
    activo              BOOLEAN DEFAULT TRUE
);
 
-- ---------- 3. Pedido ----------
CREATE TABLE pedido (
    id                      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id              INT NOT NULL REFERENCES cliente(id),
    categoria_id            INT REFERENCES categoria_trabajo(id),
    descripcion             TEXT,
    estado                  VARCHAR(20) NOT NULL DEFAULT 'pendiente'
                            CHECK (estado IN ('pendiente', 'en_proceso', 'terminado', 'entregado')),
    fecha_registro          TIMESTAMP DEFAULT NOW(),
    fecha_entrega_estimada  DATE,
    fecha_entrega_real      DATE,
    precio_total            NUMERIC(12,2)    -- PRIVADO: la API nunca lo devuelve
);
 
-- ---------- 4. Galería ----------
CREATE TABLE trabajo_galeria (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id    INT NOT NULL REFERENCES categoria_trabajo(id),
    titulo          VARCHAR(150) NOT NULL,
    descripcion     TEXT,
    ciudad          VARCHAR(100),
    fecha_trabajo   DATE,
    destacado       BOOLEAN DEFAULT FALSE,
    publicado       BOOLEAN DEFAULT TRUE,
    orden           INT DEFAULT 0,
    pedido_id       INT REFERENCES pedido(id) ON DELETE SET NULL,  -- opcional, uso interno
    fecha_creacion  TIMESTAMP DEFAULT NOW()
);
 
CREATE TABLE media_trabajo (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trabajo_id     INT NOT NULL REFERENCES trabajo_galeria(id) ON DELETE CASCADE,
    tipo           VARCHAR(10) NOT NULL CHECK (tipo IN ('imagen', 'video')),
    url            VARCHAR(500) NOT NULL,
    miniatura_url  VARCHAR(500),
    es_portada     BOOLEAN DEFAULT FALSE,
    orden          INT DEFAULT 0
);
 
-- ---------- 5. Acceso del cliente ----------
CREATE TABLE cuenta_cliente (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id      INT NOT NULL UNIQUE REFERENCES cliente(id) ON DELETE CASCADE,  -- 1 a 1
    correo          VARCHAR(150) NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,   -- BCrypt, nunca texto plano
    activo          BOOLEAN DEFAULT TRUE,
    ultimo_acceso   TIMESTAMP,
    fecha_creacion  TIMESTAMP DEFAULT NOW()
);
 
-- ---------- 6. Diseños y seguimiento ----------
CREATE TABLE propuesta_diseno (
    id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id           INT NOT NULL REFERENCES pedido(id) ON DELETE CASCADE,
    etiqueta            VARCHAR(100),            -- Opción A, Opción B...
    imagen_url          VARCHAR(500) NOT NULL,
    subido_por          INT REFERENCES usuario(id) ON DELETE SET NULL,
    estado              VARCHAR(20) NOT NULL DEFAULT 'pendiente'
                        CHECK (estado IN ('pendiente', 'aprobada', 'rechazada')),
    comentario_cliente  TEXT,                    -- motivo si rechaza
    fecha_subida        TIMESTAMP DEFAULT NOW(),
    fecha_respuesta     TIMESTAMP
);
 
CREATE TABLE historial_estado (
    id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id     INT NOT NULL REFERENCES pedido(id) ON DELETE CASCADE,
    estado        VARCHAR(20) NOT NULL
                  CHECK (estado IN ('pendiente', 'en_proceso', 'terminado', 'entregado')),
    nota_publica  VARCHAR(255),
    usuario_id    INT REFERENCES usuario(id) ON DELETE SET NULL,
    fecha         TIMESTAMP DEFAULT NOW()
);
 
